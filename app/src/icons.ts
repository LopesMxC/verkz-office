/** SVG do ícone. `slash` desenha o risco vermelho (microfone/câmera desligados). */
export function icon(name: string, size = 24, slash = false): string {
  const map = MAPS[name] ?? MAPS.apps;
  let rects = "";
  map.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  });
  let s = "";
  if (slash) for (let i = 0; i < 12; i++) s += `<rect x="${i}" y="${i}" width="1.2" height="1.2" fill="#ff4d5e"/>`;
  return `<svg class="pix-icon" width="${size}" height="${size}" viewBox="0 0 12 12" fill="currentColor">${rects}${s}</svg>`;
}
